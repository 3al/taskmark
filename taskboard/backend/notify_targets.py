"""Кого касается задача. Общий этаж уведомлений, без каналов доставки.

Повод и канал разведены намеренно. **Повод** — состояние задачи (сменился
статус, подходит срок) — про каналы не знает вовсе. **Канал** — чат, служба
уведомлений внутри инструмента, что появится дальше — сам решает, какие задачи
ему интересны, кого из причастных он умеет достать и как выглядит сообщение.

Поэтому здесь нет ни слова про телеграм: этот модуль отвечает только на вопрос
«кто причастен к задаче» и «откуда она пришла». Что с этим делать — знает канал
(`telegram_notify` — первый из них).
"""

from __future__ import annotations

# Роли причастных. Хозяин доски — тот, чей это инструмент: задачи на его доске
# делает он. Автор — тот, кто задачу принёс; у пришедшей из чата это отправитель
OWNER = "owner"
AUTHOR = "author"

# Пустое значение поля задачи. `~` — принятая в проекте запись «нет значения»
EMPTY = ("", "~", "-", "none", "null")


def _value(meta: dict, key: str) -> str:
    raw = str((meta or {}).get(key) or "").strip()
    return "" if raw.lower() in EMPTY else raw


def origin(meta: dict) -> str:
    """Откуда задача пришла. Пусто — заведена на доске или агентом.

    Значение остаётся **непрозрачным**: разбирает его тот канал, который его и
    записал. Общей части достаточно знать, что отметка есть.
    """
    return _value(meta, "origin")


def people(meta: dict) -> list[dict]:
    """Причастные к задаче — в порядке от хозяина доски к автору.

    Хозяин идёт **без значения**: кто он такой, знает канал — у чата это ник из
    настроек, у службы уведомлений внутри инструмента адресат вообще один и
    называть его незачем. Автор берётся из задачи как есть: превращать его в тег
    или в имя — тоже дело канала.

    Отсутствующего в списке нет вовсе, поэтому канал не разбирает пустые строки.
    """
    found: list[dict] = [{"role": OWNER}]
    author = _value(meta, "author")
    if author:
        found.append({"role": AUTHOR, "value": author})
    return found
