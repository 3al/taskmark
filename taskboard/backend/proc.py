"""Запуск подпроцессов без мелькающего консольного окна.

Windows выделяет консольному приложению **собственное окно**, если у родителя
консоли нет. У Taskmark это обычное состояние: автозапуск идёт через `pythonw`,
перезапуск и обновление из UI — через отсоединённый процесс. Каждый вызов
`git.exe` при этом мелькал окном поверх всех остальных, а проверка обновлений
работает по таймеру всё время, пока инструмент запущен.

`capture_output=True` от этого не спасает: он перехватывает потоки, а окно
создаётся всё равно — оно про консоль, а не про вывод.

Флаг ничего не ломает там, где консоль есть: дескрипторы ребёнок наследует
по-прежнему, поэтому вывод из терминала никуда не пропадает.
"""

from __future__ import annotations

import subprocess

# На macOS и Linux флага не существует: 0 — то же, что не передавать его вовсе
NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)


def no_window_flags(extra: int = 0) -> int:
    """`creationflags` для запуска без окна, не затирая чужие флаги.

    Вызов может нести свои (`DETACHED_PROCESS` и подобные) — их передают
    аргументом, а не заменяют этим. Отсоединённому процессу флаг, к слову,
    не нужен: Windows игнорирует его вместе с `DETACHED_PROCESS`, — но
    складывать их безопасно, и правило остаётся одно на все вызовы.
    """
    return extra | NO_WINDOW
