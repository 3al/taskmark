"""Сообщения инструмента в консоли — единственное место, где собирается строка.

Печать разбросанными `print("[taskboard] ...")` оставляла сообщения без времени:
живой запуск читается и так, а вот лог, присланный пользователем за несколько
дней (у запуска без консоли он копится в `~/.taskboard/server_<порт>.log`),
разобрать нельзя — непонятно, когда случилась ошибка и сколько раз она
повторилась.

Модуль намеренно без зависимостей и на синтаксисе старых версий: его
импортирует лаунчер, который работает до создания venv и обязан сначала
внятно сказать про слишком старый Python, а не упасть на импорте.
"""

from __future__ import annotations

import sys
import time

PREFIX = "taskboard"


def stamp(when: float | None = None) -> str:
    """Метка события: дата наравне со временем — лог живёт не одни сутки."""
    return time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(when))


def line(msg: str) -> str:
    """Готовая строка сообщения: `[taskboard 2026-09-08 16:45:12] сообщение`."""
    return f"[{PREFIX} {stamp()}] {msg}"


def log(msg: str) -> None:
    """Написать сообщение инструмента в консоль (и в файл лога, если он есть)."""
    print(printable(line(msg)), flush=True)


def printable(text: str) -> str:
    """Текст, который консоль точно возьмёт.

    В сообщение попадает и чужой вывод (ошибка git, текст из чата), а у консоли
    Windows своя кодировка: `print` с неизвестным ей символом падает
    исключением — и сообщение терялось бы вместе с тем, о чём оно.
    """
    encoding = getattr(sys.stdout, "encoding", None) or "utf-8"
    return text.encode(encoding, "replace").decode(encoding, "replace")
