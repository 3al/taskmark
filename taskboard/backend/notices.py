"""Служба уведомлений доски: короткое сообщение человеку о системном событии.

**Повод и показ разведены.** Источник события — проверка обновлений, приёмка
задач из чата, что появится дальше — вызывает `emit()` и не знает, во что
уведомление превратится: сейчас это всплывашка в углу доски, завтра может быть
системный трей или строка лога. Поэтому здесь нет ни слова про интерфейс.

**Вид события — запись в реестре `NOTICES`**, а не набор полей на месте вызова.
Реестр задаёт уровень и заголовок один раз, и новый источник добавляется
строкой в него, а не правкой службы. Неизвестный вид — исключение: молча
проглоченное уведомление хуже отсутствующего, потому что о нём никто не узнает.

**Источник бывает и снаружи процесса.** Агент живёт в терминале, а не здесь, и
зовёт службу через `POST /api/notify`. Такие виды помечены в реестре признаком
`external`; остальные снаружи не шлют — голосом проверки обновлений не должен
говорить посторонний процесс.

**Транспорт — общий SSE-канал** (`watcher.send`), тот же, по которому едут
правки файлов задач. Второй канал до браузера означал бы второе переподключение
и вторую точку отказа; уведомление отличается от «changed» только тем, что едет
разобранным JSON-объектом, а не словом.

**Канал не проектный.** Сервер один на все проекты реестра, и подписчики SSE
не разделены по ним: уведомление о событии в неоткрытом проекте доезжает до
доски так же, как о событии в активном. Поэтому источник кладёт в событие поле
`project` — показывающая сторона дописывает имя, когда проект не тот, что
открыт. Молчать о чужом проекте нельзя: задачи из чата приходят в любой
привязанный, а доска открыта на одном.

**Звук — вторая настройка источника, а не свойство уведомления.** Человек
выбирает, какой повод звучит, а служба кладёт в событие готовый ответ — как со
временем показа: показ не должен знать ни про настройки, ни про виды.

Пропущенное уведомление **теряется**: службы истории нет. Уведомление отвечает
на вопрос «что произошло **сейчас**», и повод для него всегда оставляет след
где-то ещё — задача лежит на доске, версия видна точкой в шапке. Буфер
пришлось бы дополнять границей «что уже показали», а у открытой в трёх вкладках
доски такой границы не существует.
"""

from __future__ import annotations

import json
import time
from typing import Callable

# Уровни: чем уведомление является для человека. Ими различается вид
# всплывашки, и ничего больше — решений по ним не принимают
INFO = "info"
SUCCESS = "success"
WARNING = "warning"
ERROR = "error"

# Все известные уровни. Набор закрыт: показ рисует каждый своим цветом, и
# уровень, которого он не знает, доехал бы до человека серой карточкой
LEVELS = (INFO, SUCCESS, WARNING, ERROR)

# Виды уведомлений: ключ → уровень, заголовок всплывашки, имя источника в
# настройках и признаки вида: `external` — можно ли прислать снаружи,
# `sticky` — ждут ли уведомления этого вида закрытия вместо таймера; это
# **умолчание поставки**, человек меняет его галочкой у источника. `levels` —
# вправе ли источник выбрать уровень сам.
#
# **Уровень задаёт реестр — кроме видов, где повод у каждого вызова свой.**
# У проверки обновлений один повод и один тон, а агент одним и тем же видом
# говорит и «работа готова», и «всё встало»: тон там принадлежит событию, а не
# виду. Реестр остаётся хозяином — он называет умолчание и разрешает выбор. Текст приходит от источника (в нём номер задачи, версия — то, что
# известно только на месте), заголовок задаётся здесь: он одинаков у всех
# уведомлений вида и не должен переписываться каждым вызовом по-своему.
#
# **Реестр — он же список выключателей в настройках.** Новая запись появляется
# там сама: второй перечень видов, который держат руками, разошёлся бы с этим
# молча, и выключенный источник продолжал бы говорить
NOTICES: dict[str, dict] = {
    # Проверка обновлений нашла версию свежее установленной
    "update": {"level": INFO, "title": "Доступна новая версия",
               "source": "Новая версия"},
    # Задача из чата доехала до доски — человек смотрит в другую колонку и
    # без уведомления не заметит её вовсе
    "task_from_chat": {"level": SUCCESS, "title": "Задача из чата",
                       "source": "Задачи из чата"},
    # Агент передал ход человеку: работа отдана на проверку, нужен ответ или
    # работа встала. Единственный вид, который приходит **снаружи** сервера —
    # агент живёт в терминале, а не в этом процессе
    "agent": {"level": INFO, "title": "Ход за вами",
              "source": "Сообщения агента", "external": True, "levels": True},
}

# Сколько секунд всплывашка висит без вмешательства и границы этого времени.
# Ноль осмыслен и означает «не гасить само»: уведомление ждёт, пока его
# закроют. Верх — минута: дольше висящее сообщение перестаёт быть сообщением
# о «сейчас» и превращается в мусор в углу экрана
SECONDS_RANGE: tuple[int, int] = (0, 60)

# Громкость звука уведомлений в процентах. Регулятор **один на все источники**:
# звук здесь — сигнал «посмотри на доску», а не голос конкретного повода, и
# отдельная громкость у каждого была бы настройкой ради настройки
VOLUME_RANGE: tuple[int, int] = (0, 100)

# Задержка уведомления о простое терминала, в минутах. Ноль — звать сразу.
# Верх — час: простой дольше него уже не «ждёт ответа», а брошенная сессия
IDLE_MINUTES_RANGE: tuple[int, int] = (0, 60)

# Куда уходит собранное уведомление. Подставляется при старте сервера
# (`bind`), в тестах — своей функцией: служба не обязана знать про SSE
_sender: Callable[[str], None] | None = None
# Сколько слушателей у канала. Необязателен: канал, который считать не умеет,
# отвечает «не знаю», и уведомление уходит как прежде
_listeners: Callable[[], int] | None = None


def bind(sender: Callable[[str], None] | None,
         listeners: Callable[[], int] | None = None) -> None:
    """Подключить службу к каналу доставки. `None` — отключить."""
    global _sender, _listeners
    _sender = sender
    _listeners = listeners


def audience() -> int | None:
    """Сколько слушателей у канала; `None` — канал их не считает."""
    return _listeners() if _listeners is not None else None


def external(kind: str) -> bool:
    """Можно ли прислать уведомление этого вида снаружи (`POST /api/notify`).

    **Признак реестра, а не проверка на месте приёма.** Виды, которые рождаются
    внутри сервера — найденная версия, задача из чата, — снаружи не шлют:
    иначе любой локальный процесс мог бы сказать голосом проверки обновлений,
    и человек принял бы чужое сообщение за вывод инструмента.
    """
    return bool((NOTICES.get(kind) or {}).get("external"))


def enabled(kind: str, cfg: dict | None = None) -> bool:
    """Включён ли источник `kind`.

    **Умолчание — «говорит».** В настройках хранятся только выключенные виды:
    иначе источник, появившийся после того, как человек сохранил настройки,
    молчал бы у него без единого следа — ровно то же, чем болели замороженные
    дефолты конфига.
    """
    if cfg is None:
        from .config import load_global_config

        cfg = load_global_config()
    sources = cfg.get("notice_sources") or {}
    return bool(sources.get(kind, True))


def normalize_sources(value) -> dict:
    """Привести выключатели источников к хранимому виду.

    Хранятся **только выключенные** известные виды: включённый вид — это
    отсутствие записи, и держать его в файле значит заморозить умолчание
    ровно так же, как это делали слепки дефолтов. Мусор и неизвестные ключи
    отбрасываются: реестр видов задаёт поставка, а не запрос.
    """
    if not isinstance(value, dict):
        return {}
    return {kind: False for kind in NOTICES if kind in value and not value[kind]}


def normalize_seconds(value, default: int) -> int:
    """Привести время показа к целому в допустимых границах.

    Форма шлёт числа строками, а «6» и 6 — одно и то же; «долго» и 900 — нет.
    Непонятное значение заменяется дефолтом поставки, а не отказом: настройка
    вспомогательная, и ронять из-за неё сохранение всей формы незачем.
    """
    try:
        seconds = int(value)
    except (TypeError, ValueError):
        return default
    low, high = SECONDS_RANGE
    return max(low, min(high, seconds))


def is_sticky(kind: str, cfg: dict | None = None) -> bool:
    """Ждут ли уведомления источника закрытия вместо таймера.

    Умолчание поставки (в реестре) перекрывается галочкой человека. В файле
    лежат только отличия от умолчания: слепок всех источников заморозил бы
    поставку такой, какой она была в день сохранения настроек.
    """
    default = bool((NOTICES.get(kind) or {}).get("sticky"))
    if cfg is None:
        from .config import load_global_config

        cfg = load_global_config()
    chosen = (cfg.get("notice_sticky") or {}).get(kind)
    return bool(chosen) if isinstance(chosen, bool) else default


def has_sound(kind: str, cfg: dict | None = None) -> bool:
    """Звучит ли источник `kind`.

    **Умолчание — тишина**, и в файле лежат только включённые виды. Причина
    та же, что у выключателей источников, но следствие обратное: сохранить
    слепок всех видов значит пообещать звук тому, кто его не просил, — а
    источник, появившийся после сохранения настроек, начал бы шуметь молча.
    """
    if cfg is None:
        from .config import load_global_config

        cfg = load_global_config()
    return bool((cfg.get("notice_sound") or {}).get(kind))


def normalize_sound(value) -> dict:
    """Привести выбор звука к хранимому виду: только включённые известные виды."""
    if not isinstance(value, dict):
        return {}
    return {kind: True for kind in NOTICES if value.get(kind) is True}


def normalize_volume(value, default: int) -> int:
    """Привести громкость к целому в допустимых границах.

    Тот же уговор, что и у времени показа: форма шлёт числа строками, а
    непонятное значение заменяется умолчанием поставки, а не отказом.
    """
    try:
        volume = int(value)
    except (TypeError, ValueError):
        return default
    low, high = VOLUME_RANGE
    return max(low, min(high, volume))


def normalize_idle_minutes(value, default: int) -> int:
    """Привести задержку уведомления о простое к целым минутам в границах."""
    try:
        minutes = int(value)
    except (TypeError, ValueError):
        return default
    low, high = IDLE_MINUTES_RANGE
    return max(low, min(high, minutes))


def normalize_sticky(value) -> dict:
    """Привести выбор «ждать закрытия» к хранимому виду: только отличия."""
    if not isinstance(value, dict):
        return {}
    return {kind: bool(value[kind]) for kind in NOTICES
            if isinstance(value.get(kind), bool)
            and bool(value[kind]) != bool(NOTICES[kind].get("sticky"))}


def sources_state(cfg: dict) -> list[dict]:
    """Список источников для формы настроек: ключ, имя, включён ли, что ждёт."""
    return [{"kind": kind, "label": known.get("source", known["title"]),
             "enabled": enabled(kind, cfg), "sticky": is_sticky(kind, cfg),
             "sound": has_sound(kind, cfg)}
            for kind, known in NOTICES.items()]


def level_allowed(kind: str) -> bool:
    """Вправе ли источник выбрать уровень сам — или его задаёт реестр."""
    return bool((NOTICES.get(kind) or {}).get("levels"))


def build(kind: str, text: str = "", level: str = "", **fields) -> dict:
    """Собрать уведомление вида `kind`.

    Поля сверх текста (`task`, `version`) едут как есть: их понимает та часть
    интерфейса, которая уведомление показывает, а служба их не толкует.

    `level` — тон конкретного события; принимается только у видов, которым
    реестр это разрешил, и только из известных. Пусто — уровень вида.
    """
    known = NOTICES.get(kind)
    if known is None:
        raise ValueError(f"неизвестный вид уведомления: {kind}")
    if level:
        if not level_allowed(kind):
            raise ValueError(f"вид {kind} уровень не выбирает")
        if level not in LEVELS:
            raise ValueError(f"неизвестный уровень уведомления: {level}")
    notice = {
        "event": "notice",
        "kind": kind,
        "level": level or known["level"],
        "title": known["title"],
        # Ждёт закрытия, а не тает по таймеру. Считает бэкенд: это настройка
        # человека, а показу остаётся «да» или «нет»
        "sticky": is_sticky(kind),
        # Звучит ли это уведомление. Тем же порядком: настройку читает бэкенд,
        # показ получает готовый ответ и не спрашивает про источник ничего
        "sound": has_sound(kind),
        "text": str(text or "").strip(),
        # Время события, а не показа: между ними переподключение SSE и сон
        # машины, и «только что» у них разное
        "ts": time.time(),
    }
    notice.update({k: v for k, v in fields.items() if v not in (None, "")})
    return notice


def encode(notice: dict) -> str:
    """Уведомление одной строкой: SSE везёт `data:` построчно.

    `ensure_ascii=False` — русский текст остаётся читаемым в логе и в отладчике
    браузера; переносы строк внутри текста JSON экранирует сам.
    """
    return json.dumps(notice, ensure_ascii=False)


def emit(kind: str, text: str = "", level: str = "", **fields) -> dict | None:
    """Отправить уведомление. Возвращает отправленное — или `None`, если некому.

    **Не бросает при отказе доставки.** Уведомление вспомогательно: доска
    работает и без него, а источник (создание задачи, проверка обновлений)
    падать из-за несказанного сообщения не должен. Неизвестный вид — другое
    дело: это ошибка в коде источника, и она поднимается.
    """
    notice = build(kind, text, level, **fields)
    # Выключенный источник молчит — но вид всё равно проверен реестром выше:
    # опечатка в ключе не должна выглядеть как «человек это отключил»
    if not enabled(kind):
        return None
    sender = _sender
    if sender is None:
        return None
    # Канал без подписчиков — это не доставка: истории у службы нет, и
    # уведомление, ушедшее в пустую комнату, не увидит уже никто. Отчитаться
    # об отправке значит сказать агенту, что человека позвали, — а его не звали
    if audience() == 0:
        return None
    try:
        sender(encode(notice))
    except Exception:
        return None
    return notice
