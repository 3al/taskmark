// Звук уведомления: короткий сигнал, синтезированный на месте.
//
// Файла в поставке нет намеренно — доска работает офлайн, а бинарник пришлось
// бы возить, обновлять и раздавать вместе со сборкой. Два коротких тона подряд
// дают «дзинь», который слышно рядом с клавиатурой и который не спутать со
// звуком системы.
//
// Модуль общий: сигнал зовут двое — показ всплывашки и настройки, где ползунок
// громкости даёт послушать выбранное. Вторая копия этих же осцилляторов
// разошлась бы с первой молча, и человек настраивал бы не тот звук, который
// потом услышит.

const TONES = [{ hz: 880, at: 0 }, { hz: 1320, at: 0.09 }]
const TONE_MS = 0.16
// Пиковая амплитуда при громкости 100%. Меньше половины шкалы, а не единица:
// два тона частично накладываются, и на максимуме сумма ушла бы в клиппинг —
// сигнал зазвучал бы хрипом вместо «дзинь»
const PEAK = 0.4

// Контекст один на страницу и заводится при первом звуке: созданный заранее
// остаётся suspended, потому что до жеста пользователя браузер его не пускает
let audio = null

export function playNotice(volume) {
  // Ноль — это «молчать», а не «тихо»: заводить контекст незачем
  if (!volume) return
  try {
    const Ctx = window.AudioContext || window.webkitAudioContext
    if (!Ctx) return
    audio = audio || new Ctx()
    // До первого клика по странице контекст остаётся приостановленным.
    // Отказ resume() — обычное состояние свежей вкладки, а не поломка:
    // сигнал молча пропускается, уведомление показывается как обычно
    if (audio.state === 'suspended') audio.resume().catch(() => {})
    const now = audio.currentTime
    TONES.forEach(({ hz, at }) => {
      const osc = audio.createOscillator()
      const gain = audio.createGain()
      osc.type = 'sine'
      osc.frequency.value = hz
      // Затухание, а не обрыв: щелчок в конце тона слышен отчётливее самого тона
      gain.gain.setValueAtTime((volume / 100) * PEAK, now + at)
      gain.gain.exponentialRampToValueAtTime(0.0001, now + at + TONE_MS)
      osc.connect(gain).connect(audio.destination)
      osc.start(now + at)
      osc.stop(now + at + TONE_MS)
    })
  } catch {
    // Звук вспомогателен: браузер без Web Audio, отказ автозапуска или
    // закрытый контекст не должны мешать ни показу, ни настройкам
  }
}
