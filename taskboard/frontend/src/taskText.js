// Текст задачи для человека: то, что показывается в окне и уходит в буфер.
//
// Формула одна на все точки копирования — окно задачи и контекстное меню
// карточки. Разойдись они, «скопировать содержимое» давало бы разный текст в
// зависимости от того, откуда нажали, и объяснить это было бы нечем.

// HTML-комментарии в файле задачи — служебные пометки для агентов; человеку
// они видны блоками текста и только мешают читать. Файл не трогаем: чистим
// то, что показываем и копируем
export function taskBody(task) {
  return (task?.body || '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

// Задача целиком: название и тело. Номер копируется отдельным действием —
// им зовут агента и пишут в коммит, и тащить за ним весь текст незачем
export function taskCopyText(task, taskId) {
  return `${task?.meta?.title || taskId}\n\n${taskBody(task)}`
}
